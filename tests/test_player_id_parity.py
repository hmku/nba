"""Player-id parity between Python (`fantasy.data.ids`) and the web's mirror (`web/src/lib/agentPure.ts`,
used by the external-agent API to resolve names). The fixture is generated from Python and checked here and
by `web/tests/agent.test.mjs` (tech-debt F9). Regenerate after changing ids.py: `python tests/test_player_id_parity.py`."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from fantasy.data.ids import _TRANSLIT, ALIASES, canonical_id, slugify

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "player_id_parity.json"
# Edge cases on top of every projected player's name: accents, apostrophes, translit-only letters, aliases.
EXTRA = [
    "Nikola Jokić", "Jaren Jackson Jr.", "D'Angelo Russell", "De’Aaron Fox", "Alex Sarr", "Bub Carrington",
    "Egor Dёmin", "Egor Dеmin", "Ron Holland", "Nicolas Claxton", "Bogdan Bogdanović", "Jusuf Nurkić",
    "Dāvis Bertāns", "Kristaps Porziņģis", "Moe Wagner", "  Herb  Jones ", "A/B, C-D",
    "Łukasz Ørsted Æsir Œuf ßı", "Jimmy Butler III", "Kelly Oubre", "--x--", "",
]


def build() -> dict:
    df = pd.read_csv(ROOT / "data" / "processed" / "projections_2026_27.csv", usecols=["name"])
    names = sorted(set(df["name"].dropna())) + EXTRA
    return {
        "_comment": "Generated by tests/test_player_id_parity.py from fantasy.data.ids; also checked by web/tests/agent.test.mjs.",
        "translit": {chr(k): v for k, v in sorted(_TRANSLIT.items())},
        "aliases": dict(sorted(ALIASES.items())),
        "cases": [{"name": n, "slug": slugify(n), "id": canonical_id(n)} for n in names],
    }


def test_fixture_tables_match_python():
    fx = json.loads(FIXTURE.read_text())
    assert fx["aliases"] == dict(sorted(ALIASES.items()))
    assert fx["translit"] == {chr(k): v for k, v in sorted(_TRANSLIT.items())}


def test_fixture_cases_match_python():
    for c in json.loads(FIXTURE.read_text())["cases"]:
        assert (slugify(c["name"]), canonical_id(c["name"])) == (c["slug"], c["id"]), c["name"]


if __name__ == "__main__":
    FIXTURE.write_text(json.dumps(build(), ensure_ascii=False, indent=1) + "\n")
    print(f"wrote {FIXTURE}")
